"""`project` tool: scaffold a small project and verify it.

Verify runs fixed argv (never a user-supplied command), so it does not need the shell
allowlist; the whole call is still audited by the API layer.
"""

from __future__ import annotations

import subprocess
import sys
from typing import Any

from app import sandbox

from .registry import register_tool

PY_MAIN = '''"""Generated by outworld."""


def add(a: int, b: int) -> int:
    return a + b
'''

PY_TEST = '''from app_main import add


def test_add() -> None:
    assert add(2, 3) == 5
'''

PYPROJECT = """[project]
name = "__NAME__"
version = "0.1.0"
requires-python = ">=3.11"
"""

STATIC_INDEX = """<!doctype html>
<html lang="en">
	<head>
		<meta charset="utf-8" />
		<meta name="viewport" content="width=device-width, initial-scale=1" />
		<title>__NAME__</title>
		<link rel="stylesheet" href="style.css" />
	</head>
	<body>
		<h1>__NAME__</h1>
		<script src="script.js"></script>
	</body>
</html>
"""

TEMPLATES: dict[str, dict[str, str]] = {
    "python": {
        "pyproject.toml": PYPROJECT,
        "app_main.py": PY_MAIN,
        "tests/test_main.py": PY_TEST,
        ".gitignore": "__pycache__/\n.venv/\n",
    },
    "static": {
        "index.html": STATIC_INDEX,
        "style.css": "body { font-family: system-ui; margin: 2rem; }\n",
        "script.js": "console.log('ready');\n",
    },
    "svelte": {
        "package.json": '{"name": "__NAME__", "private": true, "type": "module"}\n',
        "vite.config.ts": "export default {};\n",
        "src/routes/+page.svelte": "<h1>__NAME__</h1>\n",
    },
}


def _safe_name(name: str) -> str:
    candidate = (name or "").strip().strip('"').strip("'")
    if not candidate or candidate in {".", ".."} or "/" in candidate or "\\" in candidate:
        raise sandbox.SandboxError("invalid_name", 400)
    return candidate


@register_tool(name="project", description="Scaffold or verify a small project inside the workspace")
def run(op: str, name: str = "", template: str = "python", path: str | None = None) -> dict[str, Any]:
    try:
        project_name = _safe_name(name)
        target = sandbox.resolve(path or project_name)
    except sandbox.SandboxError as exc:
        return {"ok": False, "data": None, "meta": {}, "error": exc.code}

    if op == "scaffold":
        files = TEMPLATES.get(template)
        if files is None:
            return {"ok": False, "data": None, "meta": {}, "error": f"unknown_template:{template}"}
        if target.exists() and any(target.iterdir()):
            return {"ok": False, "data": None, "meta": {}, "error": "target_exists"}
        target.mkdir(parents=True, exist_ok=True)
        written = []
        for relative, body in files.items():
            destination = target / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(body.replace("__NAME__", project_name), encoding="utf-8")
            written.append(relative)
        return {
            "ok": True,
            "data": {"path": sandbox.relative(target), "template": template, "files": sorted(written)},
            "meta": {},
            "error": None,
        }

    if op == "verify":
        if not target.exists():
            return {"ok": False, "data": None, "meta": {}, "error": "not_found"}
        checks: list[dict[str, Any]] = []
        if (target / "pyproject.toml").exists():
            checks.append(_run_pytest(target))
        if (target / "index.html").exists():
            checks.append(
                {"name": "index.html", "ok": True, "output": "present"}
            )
        if (target / "package.json").exists():
            checks.append({"name": "package.json", "ok": True, "output": "present"})
        if not checks:
            return {"ok": False, "data": None, "meta": {}, "error": "nothing_to_verify"}
        return {
            "ok": all(check["ok"] for check in checks),
            "data": {"path": sandbox.relative(target), "checks": checks},
            "meta": {},
            "error": None,
        }

    return {"ok": False, "data": None, "meta": {}, "error": f"unknown_op:{op}"}


def _run_pytest(target) -> dict[str, Any]:
    try:
        completed = subprocess.run(  # noqa: S603 - fixed argv
            [sys.executable, "-m", "pytest", "-q", "--no-header", "-p", "no:cacheprovider"],
            cwd=str(target),
            capture_output=True,
            text=True,
            timeout=180,
            check=False,
        )
    except (subprocess.TimeoutExpired, OSError) as exc:
        return {"name": "pytest", "ok": False, "output": f"{type(exc).__name__}: {exc}"}
    output = (completed.stdout + completed.stderr).strip()
    return {"name": "pytest", "ok": completed.returncode == 0, "output": output[-2000:]}
